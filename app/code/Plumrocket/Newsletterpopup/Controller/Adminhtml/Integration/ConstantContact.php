namespace Plumrocket\Newsletterpopup\Controller\Adminhtml\Integration;

class ConstantContact extends \Plumrocket\Newsletterpopup\Controller\Adminhtml\Integration
{
    /**
     * Frontend label for integration
     */
    const RESPONSE_FRONTEND_LABEL = 'Constant Contact';

    /**
     * Test constructor.
     *
     * @param \Magento\Backend\App\Action\Context $context
     * @param \Plumrocket\Newsletterpopup\Model\Integration\ConstantContact $serviceModel
     */
    public function __construct(
        \Magento\Backend\App\Action\Context $context,
        \Plumrocket\Newsletterpopup\Model\Integration\ConstantContact $serviceModel
    ) {
        $this->serviceModel = $serviceModel;
        parent::__construct($context);
    }

    /**
     * @return \Magento\Framework\App\ResponseInterface|\Magento\Framework\Controller\ResultInterface
     */
    public function execute()
    {
        $this->responseFrontendLabel = self::RESPONSE_FRONTEND_LABEL;
        $response = $this->serviceModel->validateCredentials();

        if (true === $response) {
            $message = __('Success! Your Account is correct.');

            return $this->getResultSuccess($message);
        }

        $message = isset($response['error_message']) ? $response['error_message'] : __('Something went wrong.');

        return $this->getResultError($message);
    }
}
