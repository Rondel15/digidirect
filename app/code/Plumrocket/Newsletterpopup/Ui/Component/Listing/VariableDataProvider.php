declare(strict_types=1);

namespace Plumrocket\Newsletterpopup\Ui\Component\Listing;

use Magento\Framework\Api\FilterBuilder;
use Magento\Framework\Api\Search\ReportingInterface;
use Magento\Framework\Api\Search\SearchCriteriaBuilder;
use Magento\Framework\App\RequestInterface;
use Magento\Framework\View\Element\UiComponent\DataProvider\DataProvider;
use Plumrocket\Newsletterpopup\Model\Popup\Variable;

/**
 * @since 4.0.0
 */
class VariableDataProvider extends DataProvider
{
    /**
     * @var Variable
     */
    protected $variables;

    /**
     * VariableDataProvider constructor.
     *
     * @param string $name
     * @param string $primaryFieldName
     * @param string $requestFieldName
     * @param ReportingInterface $reporting
     * @param SearchCriteriaBuilder $searchCriteriaBuilder
     * @param RequestInterface $request
     * @param FilterBuilder $filterBuilder
     * @param Variable $variables
     * @param array $meta
     * @param array $data
     */
    public function __construct(
        string $name,
        string $primaryFieldName,
        string $requestFieldName,
        ReportingInterface $reporting,
        SearchCriteriaBuilder $searchCriteriaBuilder,
        RequestInterface $request,
        FilterBuilder $filterBuilder,
        Variable $variables,
        array $meta = [],
        array $data = []
    ) {
        parent::__construct(
            $name,
            $primaryFieldName,
            $requestFieldName,
            $reporting,
            $searchCriteriaBuilder,
            $request,
            $filterBuilder,
            $meta,
            $data
        );
        $this->variables = $variables;
    }

    /**
     * @inheritDoc
     */
    public function getData()
    {
        $items = $this->variables->getVariablesOptionArray();

        return [
            'items' => $items,
            'totalRecords' => count($items)
        ];
    }
}
